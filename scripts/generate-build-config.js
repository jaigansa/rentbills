#!/usr/bin/env node
/* RentBill Pro — generate js/core/build-config.js from environment variables.
 *
 * Reads the Supabase project URL + anon key from the environment and writes a
 * build-config.js that sets window.__RENTBILL_SB_URL__ / __RENTBILL_SB_KEY__.
 * Cloudflare Pages injects these as *encrypted* environment variables at build
 * time, so no real credential is ever committed to GitHub.
 *
 * Env vars (checked in priority order):
 *   RENTBILL_SUPABASE_URL  / RENTBILL_SUPABASE_KEY   <- recommended naming
 *   VITE_SUPABASE_URL      / VITE_SUPABASE_ANON_KEY  <- Supabase/Vite convention
 *
 * Usage:
 *   node scripts/generate-build-config.js [outPath]
 *     outPath defaults to js/core/build-config.js
 */
import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Automatically load .env file if present
for (const envFile of ['.env', '.env.local', '.env.production']) {
  const envPath = resolve(process.cwd(), envFile);
  if (existsSync(envPath)) {
    try {
      const lines = readFileSync(envPath, 'utf8').split(/\r?\n/);
      for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) continue;
        const eqIdx = trimmed.indexOf('=');
        if (eqIdx !== -1) {
          const k = trimmed.slice(0, eqIdx).trim();
          let v = trimmed.slice(eqIdx + 1).trim();
          v = v.replace(/^["']|["']$/g, '').trim();
          if (!process.env[k] && v) {
            process.env[k] = v;
          }
        }
      }
    } catch (e) {}
  }
}

function findEnv(explicitList, isUrl = false) {
  const keys = Object.keys(process.env);
  // 1. Exact match
  for (const name of explicitList) {
    const foundKey = keys.find(k => k.trim() === name);
    if (foundKey && process.env[foundKey]) {
      return { val: process.env[foundKey], name: foundKey };
    }
  }
  // 2. Fuzzy match
  for (const k of keys) {
    const cleanKey = k.trim();
    const val = (process.env[k] || '').trim();
    if (!val) continue;

    if (isUrl) {
      // Must NOT be a key variable name
      if (/key|secret|token|anon|publishable/i.test(cleanKey)) continue;
      // Must NOT be a key value format
      if (/^(sb_publishable_|eyJ)/i.test(val)) continue;
      // Must match URL keywords
      if (/supabase.*url|url.*supabase|rentbill.*url|supabase.*project|supabase.*uri|supabase.*host|supabase.*domain|rentbill.*uri|rentbill.*host|supabase.*id/i.test(cleanKey)) {
        return { val: process.env[k], name: k };
      }
    } else {
      // Key matching
      if (/supabase.*key|key.*supabase|rentbill.*key|anon.*key|publishable.*key/i.test(cleanKey)) {
        return { val: process.env[k], name: k };
      }
    }
  }
  return { val: '', name: '' };
}

function formatSupabaseUrl(input) {
  if (!input) return '';
  let s = String(input).trim().replace(/^["']|["']$/g, '').trim();
  if (!s || /^(YOUR_PROJECT_ID|YOUR_SUPABASE_URL)$/i.test(s)) return '';
  if (!s.startsWith('http://') && !s.startsWith('https://')) {
    if (s.includes('.')) {
      s = 'https://' + s;
    } else {
      s = 'https://' + s + '.supabase.co';
    }
  }
  return s.replace(/\/+$/, '');
}

const urlMatch = findEnv(
  [
    'RENTBILL_SUPABASE_URL',
    'SUPABASE_URL',
    'PUBLIC_SUPABASE_URL',
    'ASTRO_PUBLIC_SUPABASE_URL',
    'ASTRO_SUPABASE_URL',
    'VITE_SUPABASE_URL',
    'NEXT_PUBLIC_SUPABASE_URL'
  ],
  true
);

const keyMatch = findEnv(
  [
    'RENTBILL_SUPABASE_KEY',
    'SUPABASE_KEY',
    'SUPABASE_ANON_KEY',
    'PUBLIC_SUPABASE_ANON_KEY',
    'PUBLIC_SUPABASE_KEY',
    'ASTRO_PUBLIC_SUPABASE_ANON_KEY',
    'ASTRO_PUBLIC_SUPABASE_KEY',
    'SUPABASE_PUBLISHABLE_KEY',
    'VITE_SUPABASE_ANON_KEY',
    'NEXT_PUBLIC_SUPABASE_ANON_KEY'
  ],
  false
);

function sanitizeKey(val) {
  if (!val) return '';
  let s = String(val).trim().replace(/^["']|["']$/g, '').trim();
  if (/^(YOUR_KEY|YOUR_ANON_KEY)$/i.test(s)) return '';
  return s;
}

const url = formatSupabaseUrl(urlMatch.val);
const key = sanitizeKey(keyMatch.val);

const outPath = resolve(process.argv[2] || 'js/core/build-config.js');

function escapeJs(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r?\n/g, '');
}

const banner = '/* AUTO-GENERATED by scripts/generate-build-config.js — do not edit. */';
const content = [
  banner,
  "window.__RENTBILL_SB_URL__ = '" + escapeJs(url) + "';",
  "window.__RENTBILL_SB_KEY__ = '" + escapeJs(key) + "';",
  ''
].join('\n');

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, content, 'utf8');

const echoUrl = url ? url : '(unset)';
const echoKey = key ? '***injected***' : '(unset)';
console.log(`Generated ${outPath.replace(process.cwd() + '/', '')}`);
console.log(`  URL: ${echoUrl}${urlMatch.name ? ` (from ${urlMatch.name})` : ''}`);
console.log(`  Key: ${echoKey}${keyMatch.name ? ` (from ${keyMatch.name})` : ''}`);

if (!url || !key) {
  const envKeys = Object.keys(process.env).filter(k => !/^(PATH|HOME|USER|SHELL|LANG|PWD|SHLVL|_|CF_|NODE_|CI|NVM_|GOPATH|GOROOT|DEBIAN_|APT_)/i.test(k));
  console.log('  [Debug] Custom env vars visible in build container:', envKeys.length > 0 ? envKeys.join(', ') : '(none found)');
  for (const k of ['RENTBILL_SUPABASE_URL', 'RENTBILL_SUPABASE_KEY', 'SUPABASE_URL', 'SUPABASE_KEY']) {
    if (k in process.env) {
      const len = (process.env[k] || '').length;
      console.log(`  [Debug] ${k}: present in Cloudflare (${len} characters)`);
    } else {
      console.log(`  [Debug] ${k}: NOT FOUND in Cloudflare`);
    }
  }
}
