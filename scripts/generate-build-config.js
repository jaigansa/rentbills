#!/usr/bin/env node
/* RentBill Pro — generate js/core/build-config.js from environment variables.
 *
 * Reads the Supabase project URL + anon key from the environment and writes a
 * build-config.js that sets window.__RENTBILL_SB_URL__ / __RENTBILL_SB_KEY__.
 * Cloudflare Pages injects these as *encrypted* environment variables at build
 * time, so no real credential is ever committed to GitHub.
 *
 * Env vars (checked in priority order):
 *   RENTBILL_SUPABASE_URL  / RENTBILL_SUPABASE_KEY   <- recommended naming
 *   VITE_SUPABASE_URL      / VITE_SUPABASE_ANON_KEY  <- Supabase/Vite convention
 *
 * Usage:
 *   node scripts/generate-build-config.js [outPath]
 *     outPath defaults to js/core/build-config.js
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const url = process.env.RENTBILL_SUPABASE_URL || process.env.VITE_SUPABASE_URL || '';
const key = process.env.RENTBILL_SUPABASE_KEY || process.env.VITE_SUPABASE_ANON_KEY || '';

const outPath = resolve(process.argv[2] || 'js/core/build-config.js');

function escapeJs(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r?\n/g, '');
}

const banner = '/* AUTO-GENERATED by scripts/generate-build-config.js — do not edit. */';
const content = [
  banner,
  "window.__RENTBILL_SB_URL__ = '" + escapeJs(url) + "';",
  "window.__RENTBILL_SB_KEY__ = '" + escapeJs(key) + "';",
  ''
].join('\n');

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, content, 'utf8');

const src = url.replace(/^https?:\/\//, '').replace(/\.supabase\.co\/?$/, '');
const echoUrl = src ? `https://${src}.supabase.co` : '(unset)';
const echoKey = key ? '***injected***' : '(unset)';
console.log(`Generated ${outPath.replace(process.cwd() + '/', '')}`);
console.log(`  URL: ${echoUrl}`);
console.log(`  Key: ${echoKey}`);
