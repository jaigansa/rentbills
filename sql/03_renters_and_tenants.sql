-- ============================================================================

CREATE TABLE IF NOT EXISTS public.renters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    unit_id BIGINT NOT NULL REFERENCES public.units(id) ON DELETE RESTRICT,
    owner_id BIGINT REFERENCES public.owners(id) ON DELETE SET NULL,
    owner_name TEXT,
    user_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    mobile_number TEXT,
    email TEXT,
    aadhar_no TEXT,
    perm_address TEXT,
    emergency_contact TEXT,
    occupation TEXT,
    move_in_date DATE,
    advance_amount BIGINT NOT NULL DEFAULT 0,
    base_rent BIGINT NOT NULL DEFAULT 0,
    eb_unit_price BIGINT NOT NULL DEFAULT 0,
    maint_charge BIGINT NOT NULL DEFAULT 0,
    water_calc_mode TEXT NOT NULL DEFAULT 'FIXED' CHECK (water_calc_mode IN ('FIXED', 'METERED')),
    water_fixed_charge BIGINT NOT NULL DEFAULT 0,
    water_unit_price BIGINT NOT NULL DEFAULT 0,
    initial_eb BIGINT NOT NULL DEFAULT 0,
    initial_water BIGINT NOT NULL DEFAULT 0,
    pending_arrears BIGINT NOT NULL DEFAULT 0,
    assigned_upi TEXT,
    co_tenant_names TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    vacate_date DATE,
    exit_reason TEXT,
    agreement_start_date DATE,
    agreement_expiry_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ
);
