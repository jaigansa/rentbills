  END IF;

  SELECT jsonb_agg(
    jsonb_build_object(
      'user_id',          p.id,
      'username',         p.username,
      'email',            p.email,
      'role',             p.role,
      'is_disabled',      COALESCE(p.is_disabled, FALSE),
