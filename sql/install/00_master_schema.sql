-- List all users (any role)
CREATE OR REPLACE FUNCTION public.admin_list_all_users()
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, extensions
AS $$
DECLARE
  v_result JSONB;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Access denied. Only administrators can list user accounts.';
  END IF;

  SELECT jsonb_agg(
    jsonb_build_object(
      'user_id',          p.id,
      'username',         p.username,
      'email',            p.email,
      'role',             p.role,
      'is_disabled',      COALESCE(p.is_disabled, FALSE),
      'created_at',       p.created_at,
      'updated_at',       p.updated_at,
      'last_sign_in_at',  au.last_sign_in_at,
      'email_confirmed',  (au.email_confirmed_at IS NOT NULL)
    ) ORDER BY
      CASE p.role
        WHEN 'ADMIN'   THEN 1
        WHEN 'STAFF'   THEN 2
        WHEN 'AUDITOR' THEN 3
        WHEN 'TENANT'  THEN 4
        ELSE 5
      END,
      p.username NULLS LAST
  )
  INTO v_result
  FROM public.profiles p
  LEFT JOIN auth.users au ON au.id = p.id;

  RETURN COALESCE(v_result, '[]'::jsonb);
END;
$$;

-- Create user (any non-tenant role: ADMIN / STAFF / AUDITOR)
CREATE OR REPLACE FUNCTION public.admin_create_user(
  p_email     TEXT,
  p_password  TEXT,
  p_username  TEXT DEFAULT 'New User',
  p_role      TEXT DEFAULT 'STAFF'
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, extensions
AS $$
DECLARE
  v_user_id      UUID;
  v_encrypted_pw TEXT;
  v_upper_role   TEXT;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Access denied. Only administrators can create user accounts.';
  END IF;

  v_upper_role := UPPER(TRIM(p_role));
  IF v_upper_role NOT IN ('ADMIN', 'STAFF', 'AUDITOR') THEN
    RAISE EXCEPTION 'Invalid role "%". Allowed roles for this function: ADMIN, STAFF, AUDITOR. Use admin_create_tenant_user for TENANT accounts.', p_role;
  END IF;

  IF p_email IS NULL OR TRIM(p_email) = '' THEN
    RAISE EXCEPTION 'Email address is required.';
  END IF;
  IF p_password IS NULL OR LENGTH(p_password) < 6 THEN
    RAISE EXCEPTION 'Password must be at least 6 characters long.';
  END IF;

  v_encrypted_pw := extensions.crypt(p_password, extensions.gen_salt('bf'));

  SELECT id INTO v_user_id FROM auth.users WHERE LOWER(email) = LOWER(TRIM(p_email));

  IF v_user_id IS NOT NULL THEN
    UPDATE auth.users
    SET encrypted_password = v_encrypted_pw,
        email_confirmed_at = COALESCE(email_confirmed_at, NOW()),
        confirmed_at       = COALESCE(confirmed_at, NOW()),
        updated_at         = NOW()
    WHERE id = v_user_id;

    INSERT INTO public.profiles (id, username, email, role, is_disabled)
    VALUES (v_user_id, p_username, LOWER(TRIM(p_email)), v_upper_role, FALSE)
    ON CONFLICT (id) DO UPDATE SET
      role = EXCLUDED.role,
      username = EXCLUDED.username,
      email = EXCLUDED.email,
      is_disabled = FALSE,
      updated_at = NOW();
  ELSE
    v_user_id := gen_random_uuid();
    INSERT INTO auth.users (
      id, instance_id, email, encrypted_password, email_confirmed_at, confirmed_at,
      raw_app_meta_data, raw_user_meta_data, created_at, updated_at, role, aud
    ) VALUES (
      v_user_id, '00000000-0000-0000-0000-000000000000',
      LOWER(TRIM(p_email)), v_encrypted_pw, NOW(), NOW(),
      jsonb_build_object('provider', 'email', 'providers', jsonb_build_array('email')),
      jsonb_build_object('role', v_upper_role, 'username', p_username),
      NOW(), NOW(), 'authenticated', 'authenticated'
    );

    BEGIN
      INSERT INTO auth.identities (
        id, user_id, identity_data, provider, provider_id, last_sign_in_at, created_at, updated_at
      ) VALUES (
        gen_random_uuid(), v_user_id,
        jsonb_build_object('sub', v_user_id::text, 'email', LOWER(TRIM(p_email))),
        'email', LOWER(TRIM(p_email)), NOW(), NOW(), NOW()
      );
    EXCEPTION WHEN OTHERS THEN NULL;
    END;

    INSERT INTO public.profiles (id, username, email, role, is_disabled)
    VALUES (v_user_id, p_username, LOWER(TRIM(p_email)), v_upper_role, FALSE)
    ON CONFLICT (id) DO UPDATE SET
      role = EXCLUDED.role,
      username = EXCLUDED.username,
      email = EXCLUDED.email;
  END IF;

  RETURN jsonb_build_object('success', true, 'user_id', v_user_id, 'role', v_upper_role);
END;
$$;

