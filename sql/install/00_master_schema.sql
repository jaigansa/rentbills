CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN AS $$
DECLARE
  v_role TEXT;
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN FALSE;
  END IF;

  SELECT role INTO v_role FROM public.profiles WHERE id = auth.uid();

  RETURN COALESCE(v_role = 'ADMIN', FALSE);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

